DROP TABLE IF EXISTS evento_partido;
DROP TABLE IF EXISTS partido;
DROP TABLE IF EXISTS jugador;
DROP TABLE IF EXISTS equipo;
DROP TABLE IF EXISTS torneo;
DROP TABLE IF EXISTS usuario;

-- HU-01: usuarios y roles
CREATE TABLE usuario (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  VARCHAR(50)  NOT NULL UNIQUE,
    contrasena      VARCHAR(100) NOT NULL,
    rol             VARCHAR(20)  NOT NULL
        CHECK (rol IN ('ADMINISTRADOR', 'CAPITAN', 'ARBITRO'))
);

-- HU-02 / HU-03: torneos y su formato (el formato puede quedar NULL)
CREATE TABLE torneo (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    fecha_inicio  DATE         NOT NULL,
    formato       VARCHAR(30)
        CHECK (formato IN ('TODOS_CONTRA_TODOS', 'ELIMINACION_DIRECTA'))
);

-- HU-04 / HU-06: equipos y estado de inscripción
CREATE TABLE equipo (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    capitan_id  INTEGER      NOT NULL REFERENCES usuario(id),
    torneo_id   INTEGER      NOT NULL REFERENCES torneo(id),
    estado      VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO'))
);
-- No puede haber dos equipos con el mismo nombre en un torneo (sin importar mayúsculas)
CREATE UNIQUE INDEX ux_equipo_nombre_torneo ON equipo (torneo_id, LOWER(nombre));

-- HU-05: jugadores de cada equipo
CREATE TABLE jugador (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo   VARCHAR(120) NOT NULL,
    documento         VARCHAR(20)  NOT NULL,
    fecha_nacimiento  DATE         NOT NULL,
    numero_camiseta   INTEGER      NOT NULL CHECK (numero_camiseta > 0),
    equipo_id         INTEGER      NOT NULL REFERENCES equipo(id) ON DELETE CASCADE,
    UNIQUE (equipo_id, documento)
);

-- HU-07 / HU-08: partidos del calendario y su resultado
CREATE TABLE partido (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id        INTEGER     NOT NULL REFERENCES torneo(id),
    local_id         INTEGER     NOT NULL REFERENCES equipo(id),
    visitante_id     INTEGER     NOT NULL REFERENCES equipo(id),
    fecha            DATE        NOT NULL,
    ronda            INTEGER     NOT NULL,
    estado           VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO'
        CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO')),
    goles_local      INTEGER     NOT NULL DEFAULT 0,
    goles_visitante  INTEGER     NOT NULL DEFAULT 0,
    acta_cerrada     BOOLEAN     NOT NULL DEFAULT FALSE,
    CHECK (local_id <> visitante_id)
);

-- HU-08: eventos del partido (goles, tarjetas, cambios)
CREATE TABLE evento_partido (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partido_id  INTEGER     NOT NULL REFERENCES partido(id) ON DELETE CASCADE,
    tipo        VARCHAR(20) NOT NULL
        CHECK (tipo IN ('GOL', 'TARJETA_AMARILLA', 'TARJETA_ROJA', 'CAMBIO')),
    minuto      INTEGER     NOT NULL CHECK (minuto BETWEEN 0 AND 130),
    jugador_id  INTEGER     NOT NULL REFERENCES jugador(id),
    equipo_id   INTEGER     NOT NULL REFERENCES equipo(id)
);

